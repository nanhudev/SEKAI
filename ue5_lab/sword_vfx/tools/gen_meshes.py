"""SEKAI UE5 Sword VFX - VFX mesh generator (headless, no DCC needed).

Writes OBJ meshes that UE imports as static meshes for the Niagara mesh/ribbon
renderers.

UNITS - read this before changing anything:

    UE's OBJ importer takes one OBJ unit as one centimetre. The first export
    skipped that conversion and produced a 300 degree arc two centimetres
    across. Every mesh below is therefore authored in METRES and written out
    multiplied by 100, so a mesh sits at its real size in UE and a Niagara
    scale of 1.0 means 1.0. The METRE_* constants are the numbers to reason
    about; the file on disk is in centimetres.

Conventions that the systems depend on - do not change these without changing
the Niagara build:

    UV U axis  = the travel / sweep axis, always. Materials scroll and taper on U.
    UV V axis  = across the sheet.
    +Z is the sheet normal (the sheets lie in the XY plane).
    Arcs sweep from +X counter-clockwise, centred on the origin.

Meshes:
    SM_SW_ArcSheet    annulus sector, 300 deg, thin band      <- A4 major arc
    SM_SW_WaveSheet   crescent pressure sheet, tapered ends   <- A2 sword wave
    SM_SW_ScarStrip   long quad strip, 24 segments along U     <- A3 spatial scar
    SM_SW_GlintQuad   unit quad, origin centred                <- glint / mist cards

Usage:
    python gen_meshes.py [outdir]
"""
from pathlib import Path as _SekaiPath
import os as _sekai_os
_SEKAI_ROOT = _SekaiPath(_sekai_os.environ['SEKAI_ROOT']).resolve() if 'SEKAI_ROOT' in _sekai_os.environ else next(p for p in _SekaiPath(__file__).resolve().parents if (p / 'godot/project.godot').is_file())
_SEKAI_RUNTIME = _SekaiPath(_sekai_os.environ.get('SEKAI_RUNTIME_DIR', str(_SEKAI_ROOT / '.local')))
import math
import os
import sys

OUT_DEFAULT = str(_SEKAI_ROOT / 'ue5_lab/sword_vfx/source/meshes')

# metres -> centimetres, for UE
CM = 100.0

# 1 metre at scale 1.0
ARC_OUTER = 1.00
ARC_INNER = 0.86
ARC_SWEEP_DEG = 300.0
ARC_SEGS = 128

WAVE_LENGTH = 1.00
WAVE_MAX_WIDTH = 0.22
WAVE_SEGS = 96
WAVE_ROW = 5

SCAR_LENGTH = 1.00
SCAR_WIDTH = 0.06
SCAR_SEGS = 24


def write_obj(path, name, verts, uvs, faces, comments=()):
    """faces are 0-based (vertex_index, uv_index) triples.

    verts are metres; they are written out in centimetres for UE.
    """
    with open(path, "w", encoding="ascii") as fh:
        fh.write("# SEKAI UE5 Sword VFX - generated by gen_meshes.py\n")
        fh.write("# units: centimetres (UE importer: 1 OBJ unit == 1 cm)\n")
        for c in comments:
            fh.write("# %s\n" % c)
        fh.write("o %s\n" % name)
        fh.write("mtllib none\n")
        for v in verts:
            fh.write("v %.6f %.6f %.6f\n" % (v[0] * CM, v[1] * CM, v[2] * CM))
        for t in uvs:
            fh.write("vt %.6f %.6f\n" % t)
        for (a, ta, b, tb, c, tc) in faces:
            fh.write("f %d/%d %d/%d %d/%d\n" % (a + 1, ta + 1, b + 1, tb + 1,
                                                c + 1, tc + 1))
    return path


def arc_sheet():
    """Thin annulus sector. U runs along the sweep, V across the band."""
    verts, uvs, faces = [], [], []
    for i in range(ARC_SEGS + 1):
        t = i / ARC_SEGS
        ang = math.radians(ARC_SWEEP_DEG) * t
        ca, sa = math.cos(ang), math.sin(ang)
        for j, r in enumerate((ARC_INNER, ARC_OUTER)):
            verts.append((r * ca, r * sa, 0.0))
            uvs.append((t, float(j)))
    row = 2
    for i in range(ARC_SEGS):
        a = i * row
        b = (i + 1) * row
        # inner0 outer1 -> two tris, wound so +Z faces the viewer
        faces.append((a, a, b, b, b + 1, b + 1))
        faces.append((a, a, b + 1, b + 1, a + 1, a + 1))
    return verts, uvs, faces


def wave_sheet():
    """Crescent pressure sheet: leading edge is an arc, body trails behind.

    Width goes to zero at both ends so the sheet has a real start and end
    instead of a cut-off rectangle - this is what lets A2 read as a wave.
    """
    verts, uvs, faces = [], [], []
    arc_r = WAVE_LENGTH * 0.5
    sag = WAVE_LENGTH * 0.10

    for i in range(WAVE_SEGS + 1):
        t = i / WAVE_SEGS
        ang = math.pi * (-0.62 + 1.24 * t)
        ca, sa = math.cos(ang), math.sin(ang)
        # leading edge point on the arc
        lx = arc_r * ca
        ly = arc_r * sa - sag
        # trailing direction: back along the arc's inward normal, i.e. toward
        # the chord, so the sheet is a crescent rather than a flat ribbon
        nx, ny = -ca, -sa
        w = WAVE_MAX_WIDTH * (math.sin(math.pi * t) ** 0.72)
        rot = math.radians(14.0)
        cr, sr = math.cos(rot), math.sin(rot)
        dx = nx * cr - ny * sr
        dy = nx * sr + ny * cr

        for j in range(WAVE_ROW + 1):
            v = j / WAVE_ROW
            # curvature: the trailing rows curve away more than linear
            vv = v ** 1.35
            verts.append((lx + dx * w * vv, ly + dy * w * vv, 0.0))
            uvs.append((t, 1.0 - v))
    row = WAVE_ROW + 1
    for i in range(WAVE_SEGS):
        for j in range(WAVE_ROW):
            a = i * row + j
            b = (i + 1) * row + j
            faces.append((a, a, b, b, b + 1, b + 1))
            faces.append((a, a, b + 1, b + 1, a + 1, a + 1))
    return verts, uvs, faces


def scar_strip():
    """Long quad strip. Subdivided along U so it can be bent or vertex-shaded.

    Slight bow along the length: a scar cut by a sweeping blade is never
    perfectly straight.
    """
    verts, uvs, faces = [], [], []
    bow = SCAR_WIDTH * 0.5
    for i in range(SCAR_SEGS + 1):
        t = i / SCAR_SEGS
        x = (t - 0.5) * SCAR_LENGTH
        y0 = math.sin(math.pi * (t - 0.5)) * bow
        half = SCAR_WIDTH * 0.5
        verts.append((x, y0 - half, 0.0))
        verts.append((x, y0 + half, 0.0))
        uvs.append((t, 1.0))
        uvs.append((t, 0.0))
    for i in range(SCAR_SEGS):
        a = i * 2
        b = (i + 1) * 2
        faces.append((a, a, b, b, b + 1, b + 1))
        faces.append((a, a, b + 1, b + 1, a + 1, a + 1))
    return verts, uvs, faces


def glint_quad():
    """Unit quad in XY, centred on origin, +Z normal."""
    verts = [(-0.5, -0.5, 0.0), (0.5, -0.5, 0.0), (0.5, 0.5, 0.0), (-0.5, 0.5, 0.0)]
    uvs = [(0.0, 1.0), (1.0, 1.0), (1.0, 0.0), (0.0, 0.0)]
    faces = [(0, 0, 1, 1, 2, 2), (0, 0, 2, 2, 3, 3)]
    return verts, uvs, faces


MESHES = {
    "SM_SW_ArcSheet": (arc_sheet, ["A4 major arc. %g deg sweep, inner %.2f m outer %.2f m, "
                                   "U along sweep, V across band."
                                   % (ARC_SWEEP_DEG, ARC_INNER, ARC_OUTER)]),
    "SM_SW_WaveSheet": (wave_sheet, ["A2 sword wave. Leading edge arc, tapered ends."]),
    "SM_SW_ScarStrip": (scar_strip, ["A3 spatial scar. Straight-ish sliver, U along length."]),
    "SM_SW_GlintQuad": (glint_quad, ["Generic card for glint / mist / sprite work."]),
}


def bounds(verts):
    xs = [v[0] for v in verts]
    ys = [v[1] for v in verts]
    zs = [v[2] for v in verts]
    return (min(xs), max(xs)), (min(ys), max(ys)), (min(zs), max(zs))


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else OUT_DEFAULT
    os.makedirs(out, exist_ok=True)
    for name, (fn, comments) in MESHES.items():
        v, t, f = fn()
        path = os.path.join(out, name + ".obj")
        write_obj(path, name, v, t, f, comments)
        bx, by, bz = bounds(v)
        tris = len(f)
        print("%-18s verts=%-5d tris=%-5d  size= %.2f x %.2f x %.2f m" % (
            name, len(v), tris, bx[1] - bx[0], by[1] - by[0], bz[1] - bz[0]))
    print("meshes -> " + out)


if __name__ == "__main__":
    main()
