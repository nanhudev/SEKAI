/* ============================================================================
   LOADING —— 超过 3s 的等待才给画面（PASS 05）
   ----------------------------------------------------------------------------
   规则（用户 2026-09-28）：**加载动画只出现在需要加载超过 3s 的页面上。**
   所以策略不是"等待一开始就歪一根线"，而是：
     · thresholdMs = 3000：等待跨过 3s，加载符号才现身。
       之前的任何一秒，画面保持安静（世界活着，没有 animatronic 提示）。
     · minVisibleMs = 900：一旦现身就至少活这么久 —— 否则会出现"一闪就走"，
       而一闪比不出更难看（它是闪，不是信息）。
     · 从不显示百分比 / 状态词（"LOADING CORE"/"SYNCHRONIZING" 在 §10 里被禁）：
       这条移动的笔触表示"世界还在被写"，不假装知道 Godot 内部进度多少。

   整个 BA/Godot 侧将来用同一组数（emit_tokens 会把 V1 的表导出，
   V2 的这张表现在由 components/loading_glyph.js 直接消费）。
   ========================================================================= */
